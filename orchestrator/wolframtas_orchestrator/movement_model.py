"""Derive the per-tick movement arrays (imux/imuz retention, mmu magnitude) the
Mathematica stage optimizes against, from a movement_plan.

This no longer derives the physics: the imu (retention) and mmu (base movement)
constants are read from ``movement_constants.json`` — the SINGLE source of truth
generated by ``tools/gen_movement_constants.py`` (numpy float32) and shared,
value-for-value, with the C++ exact solver (movement_constants_generated.hpp).
This module only assembles those constants per slot: it picks the retention for
the medium and composes the velocity magnitude the Wolfram model uses for a tick
(base movement * input factor, plus the sprint-jump boost). The C++ solver stores
the *base* movement and does this same composition inside ``simulate()``; here we
fold it into a single magnitude because the Mathematica model wants speed-along-
the-facing directly.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

_TABLE_PATH = Path(__file__).resolve().parent / "movement_constants.json"


@lru_cache(maxsize=1)
def _table() -> dict[str, Any]:
    return json.loads(_TABLE_PATH.read_text(encoding="utf-8"))


def retention_for(medium: str) -> float:
    table = _table()["retention"]
    if medium not in table:
        raise ValueError(f"unsupported retention medium: {medium!r}")
    return float(table[medium])


def _base_movement_key(acceleration_medium: str, retention_medium: str, sprint: bool) -> str:
    if acceleration_medium == "ground":
        return f"ground_{retention_medium}_{'sprint' if sprint else 'walk'}"
    if acceleration_medium == "air":
        return "air_sprint" if sprint else "air_walk"
    if acceleration_medium in ("water", "lava"):
        return acceleration_medium
    raise ValueError(f"unsupported acceleration medium: {acceleration_medium!r}")


def _input_factor_key(is_45: bool, sneak: bool) -> str:
    if is_45:
        return "forward_45_sneak" if sneak else "forward_45"
    return "no45_sneak" if sneak else "no45"


def _effective_sprint(slot: dict[str, Any]) -> bool:
    # Mirrors the C++ slot_effective_sprint: the raw sprint input (sneak does not
    # clear an already-true sprint attribute), and init slots never sprint.
    if slot.get("kind", "movement") == "init":
        return False
    return bool(slot.get("controls", {}).get("sprint", False))


def derive_movement_model(movement_plan: dict[str, Any]) -> dict[str, Any]:
    slots = movement_plan.get("slots")
    if not isinstance(slots, list) or not slots:
        raise ValueError("movement_plan.slots must be a non-empty list")

    table = _table()
    boost = float(table["sprintjump_boost"])

    imux: list[float] = []
    imuz: list[float] = []
    mmu: list[float] = []
    for index, slot in enumerate(slots):
        if slot.get("kind", "movement") == "init":
            imux.append(float(slot["imux"]))
            imuz.append(float(slot["imuz"]))
            mmu.append(float(slot["speed"]))
            continue

        retention = retention_for(slot.get("retention", {}).get("medium"))
        wall_axes = set(slot.get("wall_hit", {}).get("axes", []))
        imux.append(0.0 if "x" in wall_axes else retention)
        imuz.append(0.0 if "z" in wall_axes else retention)

        prev_sprint = _effective_sprint(slots[index - 1]) if index > 0 else False
        mmu.append(_derive_mmu(slot, table, boost, prev_sprint))
    return {"arrays": {"imux": imux, "imuz": imuz, "mmu": mmu}}


def derive_simulation_arrays(movement_plan: dict[str, Any]) -> dict[str, list[float]]:
    return derive_movement_model(movement_plan)["arrays"]


def derive_movement_arrays(movement_plan: dict[str, Any]) -> dict[str, list[float]]:
    return derive_simulation_arrays(movement_plan)


def _derive_mmu(slot: dict[str, Any], table: dict[str, Any], boost: float, prev_sprint: bool) -> float:
    controls = slot.get("controls", {})
    forward = int(controls.get("forward", 0))
    strafe = int(controls.get("strafe", 0))
    if forward == 0 and strafe == 0:
        return 0.0
    if forward != 1 or abs(strafe) > 1:
        raise ValueError(f"unsupported movement input: forward={forward}, strafe={strafe}")

    acceleration = slot.get("acceleration", {})
    acceleration_medium = acceleration.get("medium")
    retention_medium = slot.get("retention", {}).get("medium")
    sneak = bool(controls.get("sneak", False))
    sprint = bool(controls.get("sprint", False))
    jump = bool(controls.get("jump", False))

    # Ground sprint is immediate; air sprint is delayed one tick (use the previous
    # slot's effective sprint), matching the C++ exact solver and mothball.
    base_sprint = prev_sprint if acceleration_medium == "air" else sprint
    base_key = _base_movement_key(acceleration_medium, retention_medium, base_sprint)
    factor_key = _input_factor_key(is_45=strafe != 0, sneak=sneak)

    magnitude = float(table["base_movement"][base_key]) * float(table["input_factor"][factor_key])
    if jump and sprint:
        magnitude += boost
    return magnitude
